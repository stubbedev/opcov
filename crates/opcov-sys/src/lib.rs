#[repr(C)]
#[derive(Debug)]
pub struct ArgInfo<const N: usize> {
    returns: zend_internal_arg_info,
    arguments: [zend_internal_arg_info; N],
}

// SAFETY: an ArgInfo is immutable after its const construction and only read by the engine; the
// pointers it holds are null or a required-argument count, never dereferenced as shared data.
unsafe impl<const N: usize> Sync for ArgInfo<N> {}

impl<const N: usize> ArgInfo<N> {
    #[expect(
        clippy::as_conversions,
        clippy::cast_possible_truncation,
        reason = "a const context cannot use TryFrom; the assertion above the cast rules out truncation"
    )]
    const ARGUMENT_COUNT: u32 = {
        assert!(
            N <= u32::MAX as usize,
            "argument count must fit zend_function_entry.num_args"
        );
        N as u32
    };

    #[must_use]
    pub const fn new(
        required_arguments: usize,
        return_type_mask: u32,
        arguments: [zend_internal_arg_info; N],
    ) -> Self {
        return Self {
            returns: zend_internal_arg_info {
                name: ptr::without_provenance(required_arguments),
                type_: zend_type {
                    ptr: ptr::null_mut(),
                    type_mask: return_type_mask,
                },
                default_value: ptr::null(),
            },
            arguments,
        };
    }
}

impl ArgInfo<0> {
    #[must_use]
    pub const fn returning(return_type_mask: u32) -> Self {
        return Self::new(0, return_type_mask, []);
    }
}

#[must_use]
pub const fn argument(name: &'static CStr, type_mask: u32) -> zend_internal_arg_info {
    return zend_internal_arg_info {
        name: name.as_ptr(),
        type_: zend_type {
            ptr: ptr::null_mut(),
            type_mask,
        },
        default_value: ptr::null(),
    };
}

#[must_use]
pub const fn optional_argument(
    name: &'static CStr,
    type_mask: u32,
    default: &'static CStr,
) -> zend_internal_arg_info {
    return zend_internal_arg_info {
        default_value: default.as_ptr(),
        ..argument(name, type_mask)
    };
}

#[must_use]
pub const fn function_entry<const N: usize>(
    name: &'static CStr,
    handler: FunctionHandler,
    arg_info: &'static ArgInfo<N>,
) -> zend_function_entry {
    return zend_function_entry {
        fname: name.as_ptr(),
        handler: Some(handler),
        arg_info: &raw const arg_info.returns,
        num_args: ArgInfo::<N>::ARGUMENT_COUNT,
        flags: 0,
        frameless_function_infos: ptr::null(),
        doc_comment: ptr::null(),
    };
}

#[repr(C)]
#[derive(Debug)]
pub struct FunctionTable<const N: usize> {
    entries: [zend_function_entry; N],
    end: zend_function_entry,
}

// SAFETY: a FunctionTable is immutable after its const construction; the engine only reads it, and
// every pointer in it refers to 'static data that is itself immutable.
unsafe impl<const N: usize> Sync for FunctionTable<N> {}

impl<const N: usize> FunctionTable<N> {
    #[must_use]
    pub const fn new(entries: [zend_function_entry; N]) -> Self {
        return Self {
            entries,
            end: zend_function_entry {
                fname: ptr::null(),
                handler: None,
                arg_info: ptr::null(),
                num_args: 0,
                flags: 0,
                frameless_function_infos: ptr::null(),
                doc_comment: ptr::null(),
            },
        };
    }

    const fn as_ptr(&'static self) -> *const zend_function_entry {
        return (&raw const self.entries).cast();
    }
}

#[expect(
    clippy::as_conversions,
    clippy::cast_possible_truncation,
    reason = "a const context cannot use TryFrom; the assertion above each cast rules out truncation"
)]
const fn ini_lengths(name: &CStr, default: &CStr) -> (u16, u32) {
    let name_length = name.count_bytes();
    let value_length = default.count_bytes();
    assert!(
        name_length <= u16::MAX as usize,
        "an INI name must fit zend_ini_entry_def.name_length"
    );
    assert!(
        value_length <= u32::MAX as usize,
        "an INI default must fit zend_ini_entry_def.value_length"
    );
    return (name_length as u16, value_length as u32);
}

#[must_use]
pub const fn ini_entry(
    name: &'static CStr,
    default: &'static CStr,
    modifiable: u8,
) -> zend_ini_entry_def {
    let (name_length, value_length) = ini_lengths(name, default);
    return zend_ini_entry_def {
        name: name.as_ptr(),
        on_modify: None,
        mh_arg1: ptr::null_mut(),
        mh_arg2: ptr::null_mut(),
        mh_arg3: ptr::null_mut(),
        value: default.as_ptr(),
        displayer: None,
        value_length,
        name_length,
        modifiable,
    };
}

