#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum VmKind {
    Call,
    Switch,
    Goto,
    Hybrid,
    #[cfg(not(php_version = "8.4"))]
    Tailcall,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct UnknownVmKind(pub c_int);

impl VmKind {
    #[must_use]
    pub const fn name(self) -> &'static CStr {
        return match self {
            Self::Call => c"CALL",
            Self::Switch => c"SWITCH",
            Self::Goto => c"GOTO",
            Self::Hybrid => c"HYBRID",
            #[cfg(not(php_version = "8.4"))]
            Self::Tailcall => c"TAILCALL",
        };
    }
}

impl TryFrom<c_int> for VmKind {
    type Error = UnknownVmKind;

    fn try_from(raw: c_int) -> Result<Self, Self::Error> {
        return match raw {
            ZEND_VM_KIND_CALL => Ok(Self::Call),
            ZEND_VM_KIND_SWITCH => Ok(Self::Switch),
            ZEND_VM_KIND_GOTO => Ok(Self::Goto),
            ZEND_VM_KIND_HYBRID => Ok(Self::Hybrid),
            #[cfg(not(php_version = "8.4"))]
            ZEND_VM_KIND_TAILCALL => Ok(Self::Tailcall),
            _ => Err(UnknownVmKind(raw)),
        };
    }
}

